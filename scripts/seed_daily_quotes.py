def get_token():
    req = urllib.request.Request(
        f"{BASE_URL}/auth/login/email",
        data=json.dumps({"email": LOGIN_EMAIL, "password": LOGIN_PASSWORD}).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    with urllib.request.urlopen(req) as resp:
        data = json.loads(resp.read().decode("utf-8"))
        return data["access_token"]


def create_quote(token, content, author):
    payload = {"content": content, "author": author, "is_published": True}
    req = urllib.request.Request(
        f"{BASE_URL}/daily-quotes",
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json", "Authorization": f"Bearer {token}"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(req) as resp:
            return json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        body = e.read().decode("utf-8")
        print(f"创建失败: {content[:20]}... {body}")
        return None


